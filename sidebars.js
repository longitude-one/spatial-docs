import { existsSync, readdirSync } from 'node:fs';
import { libraryCategories } from './scripts/navbar-items.mjs';

const autogenerated = (dirName) => ({ type: 'autogenerated', dirName });
const spatialTypesV1Items = [
  'spatial-types/v1/index',
  'spatial-types/v1/spatial-builder',
  {
    type: 'category', label: 'Spatial Factories', collapsible: true, collapsed: true,
    items: [autogenerated('spatial-types/v1/spatial-factories')],
  },
  {
    type: 'category', label: 'Mutability and Immutability', collapsible: true, collapsed: true,
    items: [autogenerated('spatial-types/v1/mutability-and-immutability')],
  },
  'spatial-types/v1/spatial-reference-systems',
  {
    type: 'category', label: 'Spatial types', collapsible: true, collapsed: true,
    items: ['spatial-types/v1/instantiable-spatial-types', autogenerated('spatial-types/v1/types')],
  },
  'spatial-types/v1/validators',
];
const sidebars = {
  docsSidebar: ['intro', {
    type: 'category', label: 'About', items: [autogenerated('about')],
  }, {
    type: 'category', label: 'Shared', items: [autogenerated('shared')],
  }, ...['fr', 'en'].filter((language) => existsSync(`docs/legal-notice.${language}.md`)).map((language) => `legal-notice.${language}`)],
  standardsSidebar: [autogenerated('standards')],
  conceptsSidebar: [autogenerated('concepts')],
  dbmsSidebar: [autogenerated('dbms')],
};

// Discover documented majors from sources, independently of release status.
for (const [library, label] of libraryCategories.flatMap(({ libraries }) => libraries)) {
  if (!existsSync(`docs/${library}/index.md`)) continue;
  sidebars[`${library}Overview`] = [`${library}/index`];
  for (const entry of readdirSync(`docs/${library}`, { withFileTypes: true })) {
    if (!entry.isDirectory() || !/^v[1-9][0-9]*$/.test(entry.name)) continue;
    sidebars[`${library}_${entry.name}`] = [{
      type: 'ref', label: `${label} overview`, id: `${library}/index`,
    }, {
      type: 'category', label: `${label} · ${entry.name}`, collapsed: false,
      items: library === 'spatial-types' && entry.name === 'v1'
        ? spatialTypesV1Items
        : [autogenerated(`${library}/${entry.name}`)],
    }];
  }
}

export default sidebars;
