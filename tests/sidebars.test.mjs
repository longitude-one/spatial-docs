import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import yaml from 'js-yaml';
import sidebars from '../sidebars.js';
import { DefaultSidebarItemsGenerator } from '@docusaurus/plugin-content-docs/lib/sidebars/generator.js';

function sidebarDocuments(items, documents) {
  return items.flatMap((item) => {
    if (typeof item === 'string') return [item];
    if (item.type === 'doc') return [item.id];
    if (item.type === 'category') {
      return [...(item.link?.type === 'doc' ? [item.link.id] : []), ...sidebarDocuments(item.items, documents)];
    }
    if (item.type === 'link' || item.type === 'ref') return [];
    if (item.type === 'autogenerated') return documents.filter((id) => id.startsWith(`${item.dirName}/`));
    throw new Error(`Unsupported sidebar item type: ${item.type}`);
  });
}

test('Concepts uses an overview and flat topic pages like DBMS', async () => {
  const concepts = sidebars.conceptsSidebar;
  const topics = ['geometries', 'dimensions', 'crs', 'formats'];
  assert.deepEqual(concepts, [{ type: 'autogenerated', dirName: 'concepts' }]);
  const entries = await readdir(new URL('../docs/concepts/', import.meta.url), { withFileTypes: true });
  assert.deepEqual(entries.map((entry) => entry.name).sort(), ['index.md', ...topics.map((topic) => `${topic}.md`)].sort());
  assert.ok(entries.every((entry) => entry.isFile()), 'Concept references must be files directly under docs/concepts/');
});

test('the documentation menu includes every published source page and no missing pages', async () => {
  const docsDirectory = new URL('../docs/', import.meta.url);
  const publishedIds = [];
  for (const filename of await readdir(docsDirectory, { recursive: true })) {
    if (!filename.endsWith('.md') || filename.split(path.sep).some((part) => part.startsWith('_'))) continue;
    const source = await readFile(new URL(filename.split(path.sep).join('/'), docsDirectory), 'utf8');
    const frontMatter = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(source);
    assert.ok(frontMatter, `${filename} must have front matter`);
    const metadata = yaml.load(frontMatter[1]);
    if (metadata.draft || metadata.unlisted) continue;
    const directory = path.dirname(filename);
    const basename = metadata.id ?? path.basename(filename, '.md');
    publishedIds.push(directory === '.' ? basename : `${directory.split(path.sep).join('/')}/${basename}`);
  }

  const menuIds = Object.values(sidebars).flatMap((items) => sidebarDocuments(items, publishedIds));
  assert.deepEqual(menuIds.sort(), publishedIds.sort(),
    'Every published document must be reachable from the documentation menu');
});

test('native generation honors categories, overview order and future nested topic discovery without generated indexes', async () => {
  const metadata = JSON.parse(await readFile(new URL('../docs/standards/iso/_category_.json', import.meta.url)));
  const docs = ['standards/iso/index', 'standards/iso/iso-19111', 'standards/iso/new-topic'].map((id) => ({
    id, title: id, source: `@site/docs/${id}.md`, sourceDirName: 'standards/iso',
    frontMatter: id.endsWith('/index') ? { sidebar_label: 'Overview' } : {},
    sidebarPosition: id.endsWith('/index') ? 1 : undefined,
  }));
  const generated = await DefaultSidebarItemsGenerator({
    item: { type: 'autogenerated', dirName: 'standards' }, docs,
    categoriesMetadata: { 'standards/iso': metadata },
    numberPrefixParser: (filename) => ({ filename }),
    isCategoryIndex: ({ fileName }) => fileName === 'index',
  });
  assert.equal(generated[0].label, 'ISO');
  assert.equal(generated[0].collapsible, true);
  assert.equal(generated[0].link.type, 'doc');
  assert.equal(generated[0].link.id, 'standards/iso/index');
  assert.ok(generated[0].items.some((item) => item.id === 'standards/iso/new-topic'));
});


test('library majors and reference domains have independent native sidebar membership', () => {
  for (const [name, items] of Object.entries(sidebars)) {
    if (!/_[v][1-9][0-9]*$/.test(name)) continue;
    const [overview, category] = items;
    const [library, version] = name.split('_');
    assert.equal(overview.type, 'ref');
    assert.equal(overview.id, `${library}/index`);
    assert.equal(category.collapsed, false);
    assert.deepEqual(category.items, [{ type: 'autogenerated', dirName: `${library}/${version}` }]);
    assert.ok(category.label.endsWith(` · ${version}`));
  }
  assert.deepEqual(sidebars.standardsSidebar, [{ type: 'autogenerated', dirName: 'standards' }]);
  assert.deepEqual(sidebars.dbmsSidebar, [{ type: 'autogenerated', dirName: 'dbms' }]);
});
